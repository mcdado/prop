fn resolver(
    id: &str,
    name: &str,
    address: IpAddr,
    region: &str,
    country: &str,
    provider: &str,
    tags: &[&str],
) -> ResolverConfig {
    ResolverConfig {
        id: id.to_string(),
        name: name.to_string(),
        address,
        region: region.to_string(),
        country: country.to_string(),
        provider: provider.to_string(),
        enabled: true,
        tags: tags.iter().map(|tag| tag.to_string()).collect(),
    }
}
